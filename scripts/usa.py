def color_char(ch, col_index):
    if ch == ":":
        return f"{BLUE}{ch}{RESET}"
    if ch in { ";", "=", "(", ")"}:
        return f"{GOLD}{ch}{RESET}"
    if ch == " " or ch.isalpha():
        return ch  # keep spacing clean

    # alternate vertical stripes (red/white) by column
    if col_index % 2 == 0:
        return f"{RED}{ch}{RESET}"
    else:
        return f"{WHITE}{ch}{RESET}"

for line in art:
    colored_line = "".join(color_char(ch, i) for i, ch in enumerate(line))
    print(colored_line)

